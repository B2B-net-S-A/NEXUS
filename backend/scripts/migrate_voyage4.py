"""Build and atomically cut over Voyage 4 Qdrant collections.

Examples:
    python -m scripts.migrate_voyage4 build --commit
    python -m scripts.migrate_voyage4 validate --gold-set-report /secure/gold.json
    python -m scripts.migrate_voyage4 bootstrap-aliases
    python -m scripts.migrate_voyage4 switch --gold-set-report /secure/gold.json
    python -m scripts.migrate_voyage4 rollback --targets-json '{...}'

``switch`` never deletes the old collections. Keep them for at least 14 days.
The gold-set report must be generated by the production matching evaluator and
contain ``{"passed": true}``; a missing report fails closed.
"""

